package plugins.quorum.Libraries.Interface.Accessibility.AccessKitBinding;

/*
    enum accesskit_action in accesskit.h 0.23.2, generated by gen_enum.py
    (see the plan). A node lists the actions it supports with
    Node.addAction; VoiceOver's requests come back through an
    ActionHandler (MacosSubclassingAdapter.forWindow). Mac.so also sends
    SHOW_CONTEXT_MENU, EXPAND and COLLAPSE itself, which AccessKit's macOS
    adapter doesn't (AccessKitRuntime.m).
*/
public enum Action {
    CLICK(0),
    FOCUS(1),
    BLUR(2),
    COLLAPSE(3),
    EXPAND(4),
    CUSTOM_ACTION(5),
    DECREMENT(6),
    INCREMENT(7),
    HIDE_TOOLTIP(8),
    SHOW_TOOLTIP(9),
    REPLACE_SELECTED_TEXT(10),
    SCROLL_DOWN(11),
    SCROLL_LEFT(12),
    SCROLL_RIGHT(13),
    SCROLL_UP(14),
    SCROLL_INTO_VIEW(15),
    SCROLL_TO_POINT(16),
    SET_SCROLL_OFFSET(17),
    SET_TEXT_SELECTION(18),
    SET_SEQUENTIAL_FOCUS_NAVIGATION_STARTING_POINT(19),
    SET_VALUE(20),
    SHOW_CONTEXT_MENU(21);

    /* The C value, which the natives get (not ordinal()). */
    final int value;

    Action(int value) {
        this.value = value;
    }

    /* The constant with this C value, or null if there is none. */
    public static Action fromValue(int value) {
        for (Action action : values()) {
            if (action.value == value) {
                return action;
            }
        }
        return null;
    }
}
